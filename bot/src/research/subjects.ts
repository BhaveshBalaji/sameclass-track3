const aliases:Record<string,string>={
  'computer science':'CSE','computer science engineering':'CSE','math':'MAT','maths':'MAT',
  'biology':'BIO','english':'ENG','psych':'PSY',
};
const slash=String.fromCharCode(92);
const escape=(text:string)=>[...text].map(c=>c===slash||'^$.*+?()[]{}|'.includes(c)?slash+c:c).join('');
const names=Object.entries({...Object.fromEntries(Object.entries(ASU_SUBJECTS).map(([code,name])=>[name.toLowerCase(),code])),...aliases})
  .sort((a,b)=>b[0].length-a[0].length);
/** Full name boundaries keep chemistry and biochemistry distinct. Explicit codes take priority. */
export function subjectHints(text:string):{code:string;name:string}[]{
  const explicit=Object.keys(ASU_SUBJECTS).filter(code=>new RegExp(slash+'b'+escape(code)+slash+'b').test(text));
  if(explicit.length)return explicit.map(code=>({code,name:ASU_SUBJECTS[code]!}));
  const found=new Set<string>();let remaining=text.toLowerCase();
  for(const [name,code] of names){
    const pattern=new RegExp(slash+'b'+escape(name)+slash+'b','gi');
    if(pattern.test(remaining)){found.add(code);remaining=remaining.replace(pattern,' ');}
  }
  return [...found].map(code=>({code,name:ASU_SUBJECTS[code]!}));
}
export function expandSubjectNames(text:string):string{
  let result=text;
  for(const [name,code] of names)result=result.replace(new RegExp(slash+'b'+escape(name)+slash+'b','gi'),code);
  return result;
}
export function namedSubject(keyword:string):string|undefined{
  const match=names.find(([name])=>name===keyword.trim().toLowerCase());
  return match?.[1]??(ASU_SUBJECTS[keyword.trim().toUpperCase()]?keyword.trim().toUpperCase():undefined);
}
